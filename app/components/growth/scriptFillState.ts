/**
 * Growth > Scripts' "Fill with content" as a pure reducer (docs/spec/phase-02-button-and-popup.md; CONTEXT.md
 * › Script fill): the Fill requests in flight, the Fill dialog's last answer, and each Sequence's Fill notice with
 * its Undo list. Below it, the pure copy: `dialogFor` (the dialog's text and button), `conflictLines`,
 * `noticeCounts`, `leftNote` / `leftText`, `undoPayload` and `fillRefusalText`.
 *
 *   • One press fills: `press` records the request (the page sends at most one per (Creator, Sequence) at a time,
 *     Fill and Undo share it: its synchronous guard is the only one); `applied` records the notice, `answered` (any
 *     non-`ok` status) and `failed` open the dialog.
 *   • A request locks its whole Sequence until its answer (`inflight[fillKey]`): the page opens no edit on a row of
 *     it meanwhile, however the row got there (a Load more after the press too). A Scripts list whose last load
 *     failed locks too (the caller passes the query's error state): its rows may still show the values from before
 *     a write, until a reload succeeds; read off the query cache, so it survives a remount. `isLocked` is the rule.
 *   • Requests, notices and left notes are kept per (Creator, Sequence) (`fillKey`). Every answer carries the
 *     Creator, Sequence and request id it was made for, and acts only while that request is the one in flight for
 *     that key; otherwise it is dropped. A dialog opens only over the open Sequence of the Creator shown (`show`):
 *     a non-`ok` answer for another one ends its request and opens nothing.
 *   • An `ok` always records its notice, also for a Sequence no longer open or a Creator no longer shown: the write
 *     happened, so its Undo list is kept and the notice shows when that Creator + Sequence is opened again. A
 *     second `ok` on a Sequence with a notice appends its Undo list and adds up the counts (the server writes only
 *     still-empty Options, so write sets never overlap); a zero-write `ok` or any non-`ok` answer leaves it as is.
 *   • The dialog belongs to the open Sequence: opening another one (`show`) or another Creator (`reset`) closes it.
 *   • Notices are kept until dismissed or undone, through switching Sequence or Creator, so the Undo is never lost;
 *     each notice's Undo goes to its own Creator (`FillNotice.account`).
 *
 * The dialog is the page's one overlay together with `scriptsPageState`'s `modal`: that reducer holds this state
 * and keeps the two exclusive (`scriptsPageReducer`'s `fill` case).
 */

