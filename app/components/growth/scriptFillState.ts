/** describe-all's Describe target from this page: the Creator is brought up to it, never "1,000 more". */
export const DESCRIBE_TARGET = 1000;
const TARGET_TEXT = DESCRIBE_TARGET.toLocaleString("en-US");

export const SAVE_FIRST = "Save or close the open step first";

/** Fill needs Whole-vault access: a folder-limited chatter's button title, and a `folder_not_allowed` answer. */
export const ASK_OWNER = "Ask the owner: filling uses the whole vault";

/** `fill/plan|apply|undo`'s own error codes (`service/script_fill_api.py`) as sentences. */
const FILL_ERRORS: Readonly<Record<string, string>> = {
  sequence_not_found: "This sequence has no steps any more. It was renamed or deleted: reload the page.",
  inventory_unknown: "The vault list could not be read just now. Try again in a minute.",
  account_id_required: "Pick a Creator first.",
  folder_not_allowed: ASK_OWNER,
};

/** The sentence for a refused Fill or Undo: Fill's own error codes, else `refusalText` (never JSON or "HTTP n"). */
export function fillRefusalText(err: unknown): string {
  const code = errorCode(err);
  return (code != null ? FILL_ERRORS[code] : undefined) ?? refusalText(err);
}

/** One Sequence's Fill notice: apply's Undo list, verbatim (every write's since the notice appeared), and the
 *  counts it shows. */
export interface FillNotice {
  /** The Creator written to: the Undo goes to this `account_id`. */
  account: string | null;
  sequence: string;
  undo: FillUndoEntry[];
  /** Distinct media ids written, previews included (summed over writes). */
  n: number;
  /** Distinct Steps written (summed over writes). */
  m: number;
}

/** The rows an Undo left, by reason. */
export interface LeftCounts {
  /** `edited`: changed since the Fill. */
  changed: number;
  /** `moved` / `missing`: moved out of the Sequence or deleted. */
  moved: number;
  /** `reserved`: the Sequence is generated by a script source, so nothing was written back. */
  reserved: number;
  /** Any other reason. */
  other: number;
}

export interface FillDialogState {
  sequence: string;
  /** The request whose answer opened it: a describe refusal must belong to it. */
  req: number;
  status: FillStatus | null;
  /** A refusal sentence (an HTTP error, a refused describe start); wins over everything else. */
  refusal: string | null;
}

export interface ScriptFillState {
  /** The Creator the page shows (`reset`). */
  account: string | null;
  /** The open Sequence (`show`); null on the Tag view. */
  open: string | null;
  /** The request id in flight per `fillKey` (Fill or Undo): the Sequence's rows take no edit until it ends, so no
   *  whole-row PUT can race the write. */
  inflight: Readonly<Record<string, number>>;
  dialog: FillDialogState | null;
  /** Per `fillKey`. */
  notices: Readonly<Record<string, FillNotice>>;
  /** The last Undo's left rows per `fillKey`, while any were left. */
  left: Readonly<Record<string, LeftCounts>>;
}

interface Pin {
  account: string | null;
  sequence: string;
  req: number;
}

export type Action =
  /** The open Sequence changed (or none is open). */
  | { type: "show"; sequence: string | null }
  | ({ type: "press" } & Pin)
  | ({ type: "applied"; result: { applied: FillOption[]; undo: FillUndoEntry[] } } & Pin)
  /** Any non-`ok` apply status. */
  | ({ type: "answered"; status: FillStatus } & Pin)
  | ({ type: "failed"; message: string } & Pin)
  /** describe-all refused to start; `req`: the dialog's request. */
  | ({ type: "describeRefused"; message: string } & Pin)
  | ({ type: "undoPress" } & Pin)
  | ({ type: "undone"; result: FillUndoResult } & Pin)
  /** The notice's ×: drops the notice (and its Undo list) and any left note. */
  | { type: "dismiss"; account: string | null; sequence: string }
  | { type: "close" }
  /** Another Creator: the dialog closes; requests, notices and left notes stay under their own Creator. */
  | { type: "reset"; account: string | null };

export const INITIAL_FILL: ScriptFillState = {
  account: null, open: null, inflight: {}, dialog: null, notices: {}, left: {},
};

/** The key of one Creator's Sequence: requests, notices and left notes are kept under it. */
export function fillKey(account: string | null, sequence: string): string {
  return JSON.stringify([account, sequence]);
}

/** Whether a Creator's Sequence takes no edit: a Fill or Undo on it is in flight, or `listFailed` (that Creator's
 *  Scripts list query is in error: its rows may still show the values from before a write, W30 F41/F50). */
export function isLocked(s: ScriptFillState, account: string | null, sequence: string, listFailed: boolean): boolean {
  return listFailed || s.inflight[fillKey(account, sequence)] != null;
}

function without<T>(map: Readonly<Record<string, T>>, key: string): Record<string, T> {
  if (!(key in map)) return map;
  const rest = { ...map };
  delete rest[key];
  return rest;
}

/** The in-flight request `a` answers, ended; null when `a` is not that request for its (Creator, Sequence). */
function ended(s: ScriptFillState, a: Pin): ScriptFillState | null {
  const key = fillKey(a.account, a.sequence);
  if (s.inflight[key] !== a.req) return null;
  return { ...s, inflight: without(s.inflight, key) };
}

/** Whether `a` speaks over the dialog: its Sequence is the one open on the Creator shown. */
const shown = (s: ScriptFillState, a: Pin) => a.account === s.account && a.sequence === s.open;

export function scriptFillReducer(s: ScriptFillState, a: Action): ScriptFillState {
  switch (a.type) {
    case "show":
      if (s.open === a.sequence) return s;
      return { ...s, open: a.sequence, dialog: s.dialog?.sequence === a.sequence ? s.dialog : null };
    case "press":
    case "undoPress": {
      // No guard here: the page's synchronous one decides whether a request goes out at all.
      const key = fillKey(a.account, a.sequence);
      return { ...s, inflight: { ...s.inflight, [key]: a.req }, left: without(s.left, key) };
    }
    case "applied": {
      const e = ended(s, a);
      if (!e) return s;
      // Kept even when another Sequence or Creator is open: the write happened, and this is its only Undo.
      // ASSUMPTION: coordinator override of phase-02:112,156 (which dropped it); overturned if the owner wants the
      // spec's drop back.
      const key = fillKey(a.account, a.sequence);
      const { n, m } = noticeCounts(a.result.applied);
      const prev = e.notices[key];
      // A second write lands only on still-empty Options: its Undo list is added to the first, never replaces it.
      const notice: FillNotice = prev
        ? { ...prev, undo: [...prev.undo, ...a.result.undo], n: prev.n + n, m: prev.m + m }
        : { account: a.account, sequence: a.sequence, undo: a.result.undo, n, m };
      return {
        ...e,
        notices: { ...e.notices, [key]: notice },
        dialog: shown(s, a) && e.dialog?.sequence === a.sequence ? null : e.dialog,
      };
    }
    case "answered":
    case "failed": {
      const e = ended(s, a);
      if (!e) return s;
      if (!shown(s, a)) return e;
      const dialog: FillDialogState = a.type === "answered"
        ? { sequence: a.sequence, req: a.req, status: a.status, refusal: null }
        : { sequence: a.sequence, req: a.req, status: null, refusal: a.message };
      return { ...e, dialog };
    }
    case "describeRefused": {
      const d = s.dialog;
      if (a.account !== s.account || !d || d.sequence !== a.sequence || d.req !== a.req) return s;
      return { ...s, dialog: { ...d, refusal: a.message } };
    }
    case "undone": {
      const e = ended(s, a);
      if (!e) return s;
      const key = fillKey(a.account, a.sequence);
      const counts = leftNote(a.result);
      return {
        ...e,
        notices: without(e.notices, key),
        left: leftTotal(counts) > 0 ? { ...e.left, [key]: counts } : without(e.left, key),
      };
    }
    case "dismiss": {
      const key = fillKey(a.account, a.sequence);
      return { ...s, notices: without(s.notices, key), left: without(s.left, key) };
    }
    case "close":
      return s.dialog ? { ...s, dialog: null } : s;
    case "reset":
      // `open` stays: the page's own effect re-sends it only when the open name changes, and two Creators may
      // hold a Sequence of the same name. Requests, notices and left notes stay under their own Creator's key, so
      // an answer landing after the switch is still recorded (a write's Undo is never dropped).
      return { ...s, account: a.account, dialog: null };
  }
}

