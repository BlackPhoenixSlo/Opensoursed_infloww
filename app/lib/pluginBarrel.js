// CommonJS: next.config.ts requires this while its config runs, after Next's TS hook for the config file is gone.
/* eslint-disable @typescript-eslint/no-require-imports -- CommonJS on purpose (above) */
const fs = require("node:fs");
const path = require("node:path");

function writeBarrel(appRoot, entry, out, type, typeFrom) {
  const dir = path.join(appRoot, "plugins");
  const names = fs.existsSync(dir)
    ? fs.readdirSync(dir).filter((n) => fs.existsSync(path.join(dir, n, `${entry}.ts`))).sort()
    : [];
  const src = [
    `// Generated by lib/pluginBarrel.js from plugins/*/${entry}.ts; gitignored, do not edit.`,
    `import type { ${type} } from "${typeFrom}";`,
    ...names.map((n, i) => `import p${i} from "@/plugins/${n}/${entry}";`),
    "",
    `export const PLUGINS: readonly ${type}[] = [${names.map((_, i) => `p${i}`).join(", ")}];`,
    "",
  ].join("\n");
  const file = path.join(appRoot, "lib", out);
  let old = null;
  try {
    old = fs.readFileSync(file, "utf8");
  } catch {}
  if (old !== src) {
    const tmp = `${file}.${process.pid}.tmp`;
    fs.writeFileSync(tmp, src);
    fs.renameSync(tmp, file);
  }
  return names;
}

/** @param {string} appRoot @returns {string[]} the plugins' names */
function writePluginBarrel(appRoot) {
  writeBarrel(appRoot, "ui", "plugins.generated.ui.ts", "ChatUiPlugin", "@/lib/chatUiSlots");
  return writeBarrel(appRoot, "register", "plugins.generated.register.ts", "ChatPlugin", "@/lib/chatSlots");
}

module.exports = { writePluginBarrel };
