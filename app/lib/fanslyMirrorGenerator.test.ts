function treeHash(t: ReturnType<typeof setup>) {
  const h = createHash("sha256");
  for (const f of filesUnder(t.out)) h.update(f).update(fs.readFileSync(path.join(t.out, f)));
  for (const f of ["fansly-mirror-pages.ts", "fansly-mirror-build.ts"]) h.update(f).update(fs.readFileSync(path.join(t.lib, f)));
  return h.digest("hex");
}
