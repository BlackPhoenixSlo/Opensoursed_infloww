function setup() {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), "fansly-mirror-"));
  temps.push(root);
  const capture = path.join(root, "capture");
  fs.cpSync(path.join(FIX, "capture"), capture, { recursive: true });
  const out = path.join(root, "out", "fansly-mirror");
  const lib = path.join(root, "lib");
  const plan = path.join(capture, "mirror_plan.json");
  const run = (extra: string[] = [], env: Record<string, string> = {}) =>
    spawnSync(process.execPath, [SCRIPT, ...extra], { encoding: "utf8", env: { ...process.env, ...env } });
  const generate = (env: Record<string, string> = {}) => run(["--capture", capture, "--plan", plan, "--out", out, "--lib", lib], env);
  const check = (o = out, l = lib) => run(["--check", "--out", o, "--lib", l]);
  const manifest = () => JSON.parse(fs.readFileSync(path.join(capture, "manifest.json"), "utf8"));
  const setManifest = (edit: (m: any) => void) => {
    const m = manifest();
    edit(m);
    fs.writeFileSync(path.join(capture, "manifest.json"), JSON.stringify(m));
  };
  const setPlan = (edit: (p: any[]) => void) => {
    const p = JSON.parse(fs.readFileSync(plan, "utf8"));
    edit(p);
    fs.writeFileSync(plan, JSON.stringify(p));
  };
  const page = (rel: string) => fs.readFileSync(path.join(out, "pages", rel), "utf8");
  return { root, capture, out, lib, plan, run, generate, check, setManifest, setPlan, page };
}

function filesUnder(dir: string, prefix = ""): string[] {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .flatMap((e) => (e.isDirectory() ? filesUnder(path.join(dir, e.name), `${prefix}${e.name}/`) : [`${prefix}${e.name}`]))
    .sort();
}

