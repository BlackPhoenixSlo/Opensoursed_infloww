describe("fansly-mirror icon glyphs whose webfont was not captured", () => {
  const HIDE = ['.fa', '[class^="fa-"]', '[class*=" fa-"]'].flatMap((s) => [`${s}::before`, `${s}::after`]).join(",") + "{color:transparent!important}";
  const face = (src: string) => `@font-face{font-family:"Font Awesome 7 Pro";src:${src}}`;
  const fa = (f: string, ext = "woff2") => `url(https://assets.fansly.com/webfonts/fa-${f}.${ext}) format("${ext}")`;
  const FACES = face(fa("solid-900")) + face(fa("regular-400"));
  const SUMMARY = /^  icon glyphs hidden: /m;
  const hideStyles = (html: string) => [...html.matchAll(/<style>([^<]*)<\/style>/g)].map((m) => m[1]).filter((css) => css.includes('[class^="fa-"]'));
  const icons = ({ css = "", inline = "", second = "" }: { css?: string; inline?: string; second?: string }, captured: string[] = []) => {
    const t = setup();
    fs.appendFileSync(path.join(t.capture, "static/styles.css"), `${css}\n.fa-solid{font-family:"Font Awesome 7 Pro"}\n`);
    const profile = path.join(t.capture, "pages/profile.html");
    const extra = (inline ? `<style>${inline}</style>` : "") + (second ? '<link rel="stylesheet" href="https://assets.fansly.com/icons.css">' : "");
    fs.writeFileSync(profile, fs.readFileSync(profile, "utf8").replace("</head>", `${extra}</head>`));
    if (second) fs.writeFileSync(path.join(t.capture, "static/icons.css"), second);
    fs.mkdirSync(path.join(t.capture, "static/webfonts"));
    for (const f of captured) fs.copyFileSync(path.join(t.capture, "static/fonts/inter.woff2"), path.join(t.capture, `static/webfonts/fa-${f}.woff2`));
    t.setManifest((m) => {
      m.assets.push(...captured.map((f) => ({ url: `https://assets.fansly.com/webfonts/fa-${f}.woff2`, file: `static/webfonts/fa-${f}.woff2` })));
      if (second) m.assets.push({ url: "https://assets.fansly.com/icons.css", file: "static/icons.css" });
    });
    const r = t.generate();
    expect(r.stderr).toBe("");
    expect(r.status).toBe(0);
    return { t, r, hidden: PAGES.filter((f) => hideStyles(t.page(f)).length > 0) };
  };

  it("hides the glyphs of an icon family whose every face is missing, on every page, says so and passes --check", () => {
    const { t, r, hidden } = icons({ css: FACES });
    expect(hidden).toEqual(PAGES);
    for (const f of PAGES) expect(hideStyles(t.page(f)), f).toEqual([HIDE]);
    expect(r.stdout).toMatch(/^  icon glyphs hidden: Font Awesome 7 Pro \(2 faces missing\)$/m);
    const c = t.check();
    expect(c.stderr).toBe("");
    expect(c.status).toBe(0);
  });

  it.each([
    ["every face missing in an inline <style>", { inline: face(fa("solid-900")) }, [], "1 faces missing"],
    ["the same missing face in the copied CSS and an inline <style>", { css: FACES, inline: face(fa("solid-900")) }, [], "2 faces missing"],
    ["both icon woff2 files captured", { css: FACES }, ["solid-900", "regular-400"], null],
    ["one face of the family captured", { css: FACES }, ["regular-400"], null],
    ["missing in the copied CSS, captured in an inline <style>", { css: FACES, inline: face(fa("light-300")) }, ["light-300"], null],
    ["captured in one copied CSS file, missing in another", { css: face(fa("solid-900")), second: face(fa("regular-400")) }, ["solid-900"], null],
    ["a face with local() besides its missing url()", { css: face(`local("Font Awesome 7 Pro"),${fa("solid-900")}`) }, [], null],
    ["a face with one of two url()s captured and a unicode-range", { css: `@font-face{font-family:"Font Awesome 7 Pro";src:${fa("solid-900")},${fa("solid-900", "woff")};unicode-range:U+E000-F8FF}` }, ["solid-900"], null],
  ] as const)("%s", (_, sources, captured, missing) => {
    const { r, hidden } = icons(sources, [...captured]);
    expect(hidden).toEqual(missing ? PAGES : []);
    if (missing) expect(r.stdout).toMatch(new RegExp(`^  icon glyphs hidden: Font Awesome 7 Pro \\(${missing}\\)$`, "m"));
    else expect(r.stdout).not.toMatch(SUMMARY);
  });

  it("never hides a text font family whose faces are missing", () => {
    const { r, hidden } = icons({ css: '@font-face{font-family:"Inter Display";src:url(webfonts/display.woff2) format("woff2")}' });
    expect(hidden).toEqual([]);
    expect(r.stdout).not.toMatch(SUMMARY);
    expect(r.stdout).toMatch(/^  blanked asset ref \(missing\) in asset \/styles\.css: \/webfonts\/display\.woff2$/m);
  });
});

